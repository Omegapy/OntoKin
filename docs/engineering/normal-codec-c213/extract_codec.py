#!/usr/bin/env python3
"""Build byte-identical selected function bodies from the pinned upstream files."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def function(text, signature):
    start = text.index(signature)
    opening = text.index("{", start)
    depth = 0
    for index in range(opening, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start:index + 1] + "\n"
    raise ValueError("Unterminated upstream function")


def extract():
    mesh = (ROOT / "upstream/mesh_normals.cc").read_text()
    base = (ROOT / "upstream/BLI_math_base.hh").read_text()
    selected = {
        "unit_short_to_float": function(mesh, "MINLINE float unit_short_to_float("),
        "unit_float_to_short": function(mesh, "MINLINE short unit_float_to_short("),
        "safe_acos_approx": function(base, "inline float safe_acos_approx("),
        "corner_space_custom_data_to_normal": function(mesh, "static float3 corner_space_custom_data_to_normal("),
        "corner_space_custom_normal_to_data": function(mesh, "short2 corner_space_custom_normal_to_data("),
    }
    header = "/* Selected exact function bodies from Blender commit 32f5fdce0a0a571a39198edf8d7b5d719bf59f2c\n * SPDX-FileCopyrightText: Blender Authors\n * SPDX-License-Identifier: GPL-2.0-or-later\n * Generated by extract_codec.py; wrappers and scalar vector support live in codec_probe.cpp. */\n\n"
    header += selected["unit_short_to_float"] + "\n" + selected["unit_float_to_short"]
    header += "\nnamespace blender::math {\n" + selected["safe_acos_approx"] + "}\n"
    header += "\nnamespace blender::bke::mesh {\n"
    header += selected["corner_space_custom_data_to_normal"] + "\n"
    header += selected["corner_space_custom_normal_to_data"] + "}\n"
    return header, {name: hashlib.sha256(body.encode()).hexdigest() for name, body in selected.items()}


if __name__ == "__main__":
    header, hashes = extract()
    (ROOT / "codec_exact.inc").write_text(header)
    print(json.dumps({"selected_function_sha256": hashes}, indent=2))
