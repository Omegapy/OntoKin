#!/usr/bin/env python3
"""Package frozen, closed C038 evidence without executing product or analysis.

Root must declare the complete-input freeze before invocation. Every file in
the evidence and driver directories is included. Control selection is explicit
and every omission is recorded. Packaging/recovery/documentation command
receipts belong outside these input directories to avoid open-stream and
circular-hash artifacts. This tool does not author the checkpoint narrative.
"""
import argparse
from datetime import datetime, timezone
import fnmatch
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import sys
import time
import zipfile

MAX_MEMBERS = 4096
MAX_MEMBER_BYTES = 64 * 1024 * 1024
MAX_TOTAL_BYTES = 512 * 1024 * 1024
ZIP_DATE = (2026, 10, 25, 0, 0, 0)
COMMIT = "4ca73909f861fe4bef9694787473621c1d21c140"
TREE = "87c949b238055af1ce368c694e1d5683c8aeacde"
CORE_CONTROL = ("source-verification.json", "doc-source-inventory.json", "run-source-inventory.json",
                "execution-documentation-binding.json", "doc-original.commit", "run-original.commit",
                "capture-preexecution-review.json", "independent-census-review.json",
                "analyzer-preexecution-review.json", "analyzer-preexecution-review-002.json",
                "analyzer-syntax-preflight-002.json", "driver-syntax-preflight.json",
                "verify_source.py", "run_closed.py", "package_checkpoint.py")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def utc():
    return datetime.now(timezone.utc).isoformat()


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def json_bytes(value):
    return (json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n").encode()


def write_bytes(path, raw):
    with path.open("xb") as stream:
        stream.write(raw)


def relative_name(name):
    require(type(name) is str and name and "\\" not in name and "\0" not in name, "Invalid relative name")
    parsed = PurePosixPath(name)
    require(not parsed.is_absolute() and parsed.as_posix() == name
            and all(part not in ("", ".", "..") for part in parsed.parts), "Unsafe or noncanonical path: " + name)
    return name


def all_files(root):
    require(root.is_dir() and not root.is_symlink(), "Expected regular input directory: " + str(root))
    result = []
    for parent, directories, files in os.walk(root, followlinks=False):
        for name in directories:
            path = Path(parent) / name
            require(not path.is_symlink(), "Symlink input directory is not permitted: " + str(path))
        for name in files:
            path = Path(parent) / name
            require(path.is_file() and not path.is_symlink(), "Nonregular input file: " + str(path))
            require("__pycache__" not in path.parts and path.suffix != ".pyc", "Unidentified generated bytecode in inputs")
            relative = relative_name(path.relative_to(root).as_posix())
            result.append((relative, path))
    return sorted(result)


def fingerprint(path):
    stat = path.stat()
    return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_mode


def collect(roots, patterns, exclusions):
    data, origins, stamps, omitted = {}, {}, {}, []
    total = 0
    for namespace, root in roots.items():
        for relative, path in all_files(root):
            before = fingerprint(path)
            require(before[2] <= MAX_MEMBER_BYTES, "Input member exceeds fixed byte bound: " + relative)
            raw = path.read_bytes()
            require(before == fingerprint(path), "Input changed during read: " + relative)
            matched = [pattern for pattern in patterns if fnmatch.fnmatchcase(relative, pattern)]
            excluded = [pattern for pattern in exclusions if fnmatch.fnmatchcase(relative, pattern)]
            if namespace == "control" and (not matched or excluded):
                omitted.append({"path": relative, "bytes": len(raw), "sha256": sha(raw),
                                "reason": "explicit_exclusion" if excluded else "no_include_pattern",
                                "include_patterns_matched": matched, "exclude_patterns_matched": excluded})
                continue
            name = relative_name(namespace + "/" + relative)
            require(name not in data, "Duplicate archive member: " + name)
            total += len(raw)
            require(total <= MAX_TOTAL_BYTES and len(data) < MAX_MEMBERS, "Archive input bounds exceeded")
            data[name], origins[name], stamps[name] = raw, path, before
    return data, origins, stamps, omitted


def parse(data, name):
    require(name in data, "Required complete evidence member is absent: " + name)
    return json.loads(data[name])


def ensure_closed_streams(data, validated_analysis_report):
    """Every archived process stream must match its finalized command receipt."""
    streams, closures = [], []
    for name in sorted(data):
        if not name.startswith("execution/"):
            continue
        path = PurePosixPath(name)
        if path.name in ("stdout.txt", "stderr.txt"):
            result_name = str(path.parent / "result.json")
            receipt = parse(data, result_name)
            require(type(receipt.get("exit_code")) is int and bool(receipt.get("finished_at")),
                    "Archived output stream has no closed process receipt: " + name)
            matching = [row for row in receipt.get("streams", []) if row.get("path") == path.name]
            require(len(matching) == 1 and matching[0].get("bytes") == len(data[name])
                    and matching[0].get("sha256") == sha(data[name]), "Closed stream hash/size mismatch: " + name)
            streams.append(name)
        if path.name == "start.json":
            command_result = str(path.parent / "result.json")
            request_result = str(path.parent / "request-result.json")
            analysis_result = str(path.parent / "report.json")
            if command_result in data:
                row = parse(data, command_result)
                require(type(row.get("exit_code")) is int and bool(row.get("finished_at")),
                        "Unfinished command input: " + name)
                closures.append(command_result)
            elif request_result in data:
                row = parse(data, request_result)
                require(type(row.get("exit_code")) is int and bool(row.get("finished_receipt_at")),
                        "Unfinished request input: " + name)
                closures.append(request_result)
            elif analysis_result == validated_analysis_report:
                # bind_evidence already validates this report, its complete
                # checks and the separate closed analyzer-command receipt.
                start, row = parse(data, name), parse(data, analysis_result)
                require(start.get("schema") == row.get("schema") == "ontokin.checkpoint038-clock-analysis/0.1"
                        and start.get("status") == "failed" and row.get("status") == "passed"
                        and bool(row.get("finished_at")) and set(start) <= set(row)
                        and all(type(row[key]) is type(value) and row[key] == value
                                for key, value in start.items() if key != "status"),
                        "Standalone analysis start/report identity or closure differs: " + name)
                closures.append(analysis_result)
            else:
                raise ValueError("Unfinished or unrecognized execution start: " + name)
    return {"streams": streams, "stream_count": len(streams), "closed_results": closures,
            "method": "Closed command/request receipts, separately validated standalone analysis report, and exact stream hashes; wrappers close streams before result.json"}


def bind_evidence(data, args, packager_hash):
    pair = "execution/" + relative_name(args.pair)
    plan = parse(data, pair + "/plan.json")
    pair_result = parse(data, pair + "/pair-command.json")
    require(plan.get("order") == ["control", "capture"] and plan.get("requests_per_mode") == 1,
            "Frozen pair order/count differs")
    require(pair_result.get("processes_started") == pair_result.get("commands_closed") == 2
            and pair_result.get("outer_error") is None and pair_result.get("orchestrator_unchanged") is True,
            "Original pair is not completely closed")
    require(pair_result.get("plan_sha256") == sha(data[pair + "/plan.json"]), "Pair plan identity differs")
    require(sha(data["drivers/p16_request.py"]) == plan.get("driver_sha256")
            and sha(data["drivers/run_pair.py"]) == plan.get("orchestrator_sha256"), "Original executed driver bytes differ")
    for mode in ("control", "capture"):
        row = parse(data, pair + "/" + mode + "/request-result.json")
        require(row.get("status") == "failed" and row.get("exit_code") == 1
                and row.get("request_executed") is True and row.get("metadata_status") == "captured"
                and row.get("inputs_stable") is True and row.get("observation_preserved_counters_and_caches") is True,
                "Original failed request lacks closed intact receipts: " + mode)
        require((row.get("source_commit"), row.get("source_tree")) == (COMMIT, TREE), "Request source identity differs")
        require(row.get("capture_status") == ("captured" if mode == "capture" else "not_requested"), "Capture mode receipt differs")
    canonical_analyzer = "drivers/analyze_p16.py"
    analysis_name = "execution/" + relative_name(args.analysis_report)
    analysis = parse(data, analysis_name)
    require(analysis.get("status") == "passed" and analysis.get("neutrality_checks", {}).get("passed") is True
            and analysis.get("census_checks", {}).get("passed") is True, "Final standalone analysis has not passed")
    require(analysis.get("analyzer_sha256") == sha(data[canonical_analyzer]), "Final report does not bind included analyzer")
    require((analysis.get("source_commit"), analysis.get("source_tree")) == (COMMIT, TREE), "Analysis source identity differs")
    final_receipt_name = "execution/" + relative_name(args.analysis_receipt)
    final_receipt = parse(data, final_receipt_name)
    require(final_receipt.get("status") == "passed" and final_receipt.get("exit_code") == 0
            and final_receipt.get("inputs_stable") is True and final_receipt.get("command_files_stable") is True,
            "Final analyzer command is not closed and passing")
    require(any(row.get("sha256") == sha(data[canonical_analyzer]) and row.get("bytes") == len(data[canonical_analyzer])
                for row in final_receipt.get("command_files", [])), "Final executed analyzer hash/size not retained")
    failed_source_name = "execution/" + relative_name(args.failed_analyzer)
    failed_receipt_name = "execution/" + relative_name(args.failed_analysis_receipt)
    failed_receipt = parse(data, failed_receipt_name)
    require(failed_source_name in data and failed_receipt.get("status") == "failed"
            and type(failed_receipt.get("exit_code")) is int and failed_receipt["exit_code"] != 0,
            "Original failed analyzer attempt must remain failed and retained")
    require(any(row.get("sha256") == sha(data[failed_source_name]) and row.get("bytes") == len(data[failed_source_name])
                for row in failed_receipt.get("command_files", [])), "Failed analyzer source does not match its original command receipt")
    require(data[failed_source_name] != data[canonical_analyzer], "Failed/final analyzer identities unexpectedly identical")
    for name in (*CORE_CONTROL, *args.require_control):
        require("control/" + relative_name(name) in data, "Required selected control input is absent: " + name)
    require(sha(data["control/package_checkpoint.py"]) == packager_hash, "Packager must archive its exact own source")
    for name in (args.analysis_review, args.next_scope_review):
        review = parse(data, "control/" + relative_name(name))
        require(type(review) is dict and not review.get("blocking_findings") and not review.get("blockers"),
                "Required final review has unresolved blocking findings: " + name)
    return {"pair": pair + "/pair-command.json", "final_analysis": analysis_name,
            "final_analysis_command": final_receipt_name, "final_analyzer": canonical_analyzer,
            "failed_analysis_command": failed_receipt_name, "failed_analyzer": failed_source_name,
            "analysis_review": "control/" + args.analysis_review,
            "next_scope_review": "control/" + args.next_scope_review,
            "product_execution_commit": COMMIT, "product_execution_tree": TREE}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ("evidence", "drivers", "control", "destination", "receipt"):
        parser.add_argument("--" + flag, type=Path, required=True)
    parser.add_argument("--control-include", action="append", required=True)
    parser.add_argument("--control-exclude", action="append", default=[])
    parser.add_argument("--require-control", action="append", default=[])
    parser.add_argument("--reviewed-packager-sha256", required=True)
    parser.add_argument("--part-bytes", type=int, default=700000)
    parser.add_argument("--pair", default="pair-001")
    parser.add_argument("--analysis-report", default="analysis-002/report.json")
    parser.add_argument("--analysis-receipt", default="analysis-command-002/result.json")
    parser.add_argument("--failed-analyzer", default="analysis-command-001/analyze_p16.failed.py")
    parser.add_argument("--failed-analysis-receipt", default="analysis-command-001/result.json")
    parser.add_argument("--analysis-review", default="analyzer-result-review.json")
    parser.add_argument("--next-scope-review", default="next-scope-review.json")
    args = parser.parse_args()
    roots = {"execution": args.evidence.resolve(), "drivers": args.drivers.resolve(), "control": args.control.resolve()}
    destination, receipt_path = args.destination.resolve(), args.receipt.resolve()
    require(len(set(roots.values())) == 3, "Input roots must be distinct")
    for left in roots.values():
        require(not any(left != right and left.is_relative_to(right) for right in roots.values()), "Input roots may not overlap")
        require(not destination.is_relative_to(left) and not receipt_path.is_relative_to(left),
                "Package outputs/receipts must be outside frozen inputs")
    require(not receipt_path.is_relative_to(destination), "Packaging receipt must be outside published archive outputs")
    require(not receipt_path.exists(), "A fresh packaging receipt path is required")
    require(1 <= args.part_bytes <= 1000000, "Invalid bounded archive part size")
    patterns, exclusions = sorted(set(args.control_include)), sorted(set(args.control_exclude))
    require(all(pattern and "\\" not in pattern and "\0" not in pattern and ".." not in pattern
                and not pattern.startswith("/") for pattern in (*patterns, *exclusions)), "Invalid control glob")
    packager_hash = sha(Path(__file__).read_bytes())
    require(packager_hash == args.reviewed_packager_sha256, "Packager differs from reviewed bytes")
    receipt_path.parent.mkdir(parents=True, exist_ok=True)
    receipt = {"schema": "ontokin.checkpoint038-packaging/0.1", "status": "failed",
               "command": [sys.executable, str(Path(__file__).resolve()), *sys.argv[1:]],
               "started_at": utc(), "packager_sha256": packager_hash,
               "source_executions_repeated": False, "analysis_repeated": False,
               "release_acceptance": False, "outputs": []}
    started = time.monotonic()
    try:
        destination.mkdir(parents=True, exist_ok=True)
        require(not (destination / "checkpoint-038-manifest.json").exists()
                and not list(destination.glob("checkpoint-038-evidence.zip.part*")), "Archive targets already exist; preserve prior attempts")
        data, origins, stamps, omitted = collect(roots, patterns, exclusions)
        bindings = bind_evidence(data, args, packager_hash)
        closure = ensure_closed_streams(data, bindings["final_analysis"])
        members = [{"path": name, "bytes": len(data[name]), "sha256": sha(data[name])} for name in sorted(data)]
        archive_buffer = io.BytesIO()
        with zipfile.ZipFile(archive_buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for member in members:
                info = zipfile.ZipInfo(member["path"], date_time=ZIP_DATE)
                info.create_system = 3
                info.external_attr = 0o100644 << 16
                info.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(info, data[member["path"]], compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
        joined = archive_buffer.getvalue()
        parts = []
        for offset in range(0, len(joined), args.part_bytes):
            raw = joined[offset:offset + args.part_bytes]
            name = "checkpoint-038-evidence.zip.part%03d" % (len(parts) + 1)
            write_bytes(destination / name, raw)
            record = {"path": name, "bytes": len(raw), "sha256": sha(raw)}
            parts.append(record)
            receipt["outputs"].append(record)
        # Reopen the actual closed part files, then verify the full archive.
        recovered_parts = []
        for part in parts:
            raw = (destination / part["path"]).read_bytes()
            require(len(raw) == part["bytes"] and sha(raw) == part["sha256"], "Archive part readback differs")
            recovered_parts.append(raw)
        recovered = b"".join(recovered_parts)
        require(recovered == joined, "Joined archive readback differs")
        with zipfile.ZipFile(io.BytesIO(recovered)) as archive:
            require(archive.testzip() is None, "ZIP CRC verification failed")
            require(archive.namelist() == [row["path"] for row in members], "ZIP membership/order differs")
            for member in members:
                info = archive.getinfo(relative_name(member["path"]))
                require(not info.is_dir() and info.external_attr >> 16 == 0o100644,
                        "Unexpected ZIP member storage type")
                raw = archive.read(member["path"])
                require(len(raw) == member["bytes"] and sha(raw) == member["sha256"], "ZIP member hash/size differs")
        after, after_origins, after_stamps, after_omitted = collect(roots, patterns, exclusions)
        require(after == data and after_origins == origins and after_stamps == stamps and after_omitted == omitted,
                "Frozen input membership/bytes/storage changed during packaging")
        require(sha(Path(__file__).read_bytes()) == packager_hash, "Packager changed during execution")
        archive_record = {"format": "ZIP_DEFLATED", "compression_level": 9, "fixed_zip_timestamp": list(ZIP_DATE),
                          "parts": parts, "bytes": len(joined), "sha256": sha(joined), "member_count": len(members)}
        manifest = {"schema_version": "ontokin.checkpoint038-members/0.1", "checkpoint": 38,
                    "member_count": len(members), "uncompressed_bytes": sum(row["bytes"] for row in members),
                    "members": members, "archive": archive_record, "packager_sha256": packager_hash,
                    "selection": {"execution": "All regular files, recursively", "drivers": "All regular files, recursively",
                        "control_include": patterns, "control_exclude": exclusions,
                        "selected_control_paths": [row["path"][8:] for row in members if row["path"].startswith("control/")],
                        "omitted_control": omitted}, "bindings": bindings,
                    "closed_streams": closure,
                    "receipt_policy": "Packaging/recovery/documentation/publication receipts are stored separately after closure; this archive contains no current packaging output streams."}
        manifest_raw = json_bytes(manifest)
        manifest_name = "checkpoint-038-manifest.json"
        write_bytes(destination / manifest_name, manifest_raw)
        require((destination / manifest_name).read_bytes() == manifest_raw, "Manifest readback differs")
        receipt["outputs"].append({"path": manifest_name, "bytes": len(manifest_raw), "sha256": sha(manifest_raw)})
        receipt.update(status="passed", member_count=len(members), manifest_sha256=sha(manifest_raw), archive=archive_record,
                       closed_stream_count=closure["stream_count"], included_control_count=len(manifest["selection"]["selected_control_paths"]),
                       omitted_control_count=len(omitted), exact_membership=True, member_hashes=True, zip_crc=True,
                       part_hashes=True, joined_hash=True, input_membership_and_bytes_stable=True,
                       input_storage_stable=True, deterministic_for_identical_inputs=True)
    except BaseException as error:
        receipt["failure"] = {"type": type(error).__name__, "message": str(error)}
        raise
    finally:
        receipt.update(finished_at=utc(), elapsed_seconds=time.monotonic() - started)
        write_bytes(receipt_path, json_bytes(receipt))
    print(json.dumps({"status": receipt["status"], "members": receipt["member_count"],
                      "archive_bytes": receipt["archive"]["bytes"], "archive_sha256": receipt["archive"]["sha256"],
                      "parts": len(receipt["archive"]["parts"])}), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
