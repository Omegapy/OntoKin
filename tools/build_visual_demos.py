"""Build the two visible demonstrations from their editable OntoKin sources.

Run from any directory with Python 3.11 or later. The embedded preview data is
the exact exported GLB, so the viewer does not implement another motion model.
"""

from __future__ import annotations

import argparse
import base64
from fractions import Fraction
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ontokin.cli import _write_export
from ontokin.diagnostics import Source
from ontokin.evaluator import evaluate, exact_time, preflight
from ontokin.gltf import export_glb
from ontokin.scene import ExportOptions
from ontokin.syntax import parse
from ontokin.validator import validate


DEMOS = (
    {
        "id": "independent-parts",
        "file": "01-independent-parts.ok",
        "title": "Independent parts",
        "description": "The assembly moves while its head turns and its hand extends. Each action keeps its own timing.",
        "focus": "rig.head",
        "events": [
            {"time": 0, "label": "Three actions start"},
            {"time": 1, "label": "Head holds its 90° turn"},
            {"time": 2, "label": "Assembly and hand stop"},
        ],
    },
    {
        "id": "gravity-and-release",
        "file": "02-gravity-and-release.ok",
        "title": "Gravity and release",
        "description": "The sphere follows its carrier until release at 1 s. It then falls and keeps moving after the carrier stops at 1.25 s.",
        "focus": "payload",
        "events": [
            {"time": 0, "label": "Carrier moves with sphere"},
            {"time": 1, "label": "Grip releases the sphere"},
            {"time": 1.25, "label": "Carrier stops; sphere continues"},
        ],
    },
)


def write_reference(output_dir: Path, stem: str, model, source: Source, report: dict) -> None:
    """Record fresh semantic samples for the separate Three.js comparison."""
    times = {Fraction(index, 8) for index in range(int(model.duration * 8) + 1)}
    times.update(exact_time(time) for time in preflight(model)["boundary_times_seconds"])
    times.add(model.duration)
    samples = evaluate(model, sorted(times))["samples"]
    reference = {"schema_version": "ontokin.viewer-reference/0.1", "source_revision": source.revision,
                 "artifact_sha256": report["artifact"]["sha256"], "tolerances": report["tolerances"],
                 "samples": [{"time_seconds": sample["time_seconds"], "objects": {
                     path: {"position_m": obj["position_m"], "orientation_wxyz": obj["orientation_wxyz"]}
                     for path, obj in sample["objects"].items()}} for sample in samples]}
    (output_dir / (stem + ".reference.json")).write_text(json.dumps(reference, indent=2, allow_nan=False) + "\n", encoding="utf-8")


def build(output_dir: Path, include_conformance: bool = False) -> list[dict]:
    output_dir.mkdir(parents=True, exist_ok=True)
    previews: list[dict] = []
    for demo in DEMOS:
        source_path = ROOT / "examples/visual" / demo["file"]
        raw = source_path.read_bytes()
        source = Source(raw.decode("utf-8"), source_path.relative_to(ROOT).as_posix(), raw=raw)
        model = validate(parse(source.text, source.filename))
        result = export_glb(model, options=ExportOptions(), source_uri=source.filename, source_sha256=source.revision)
        stem = source_path.stem
        _write_export(output_dir / (stem + ".glb"), result.data, output_dir / (stem + ".export.json"), result.report)
        write_reference(output_dir, stem, model, source, result.report)
        previews.append({**demo, "source": source.text, "sourcePath": source.filename,
                         "glb": base64.b64encode(result.data).decode("ascii"), "report": result.report})
    encoded = json.dumps(previews, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    (output_dir / "demo-data.js").write_text("// Generated by tools/build_visual_demos.py; do not edit.\nwindow.ONTOKIN_DEMOS = " + encoded + ";\n", encoding="utf-8")
    if include_conformance:
        for source_path in sorted((ROOT / "docs/language-design/core-v0.1").glob("*.ok")):
            source = Source(source_path.read_text(encoding="utf-8"), source_path.relative_to(ROOT).as_posix())
            model = validate(parse(source.text, source.filename))
            result = export_glb(model, source_uri=source.filename, source_sha256=source.revision)
            _write_export(output_dir / ("core-" + source_path.stem + ".glb"), result.data,
                          output_dir / ("core-" + source_path.stem + ".export.json"), result.report)
            write_reference(output_dir, "core-" + source_path.stem, model, source, result.report)
    return previews


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "examples/visual")
    parser.add_argument("--include-conformance", action="store_true", help="Also export all four unmodified core source fixtures")
    args = parser.parse_args()
    previews = build(args.output_dir, args.include_conformance)
    print(json.dumps({"outcome": "built", "output_dir": str(args.output_dir),
                      "demonstrations": [{"id": demo["id"], "source": demo["sourcePath"],
                                           "glb_bytes": len(base64.b64decode(demo["glb"]))} for demo in previews]}, indent=2))


if __name__ == "__main__":
    main()
